package com.example.onepass.tv.data

import com.example.onepass.tv.model.TvCategory
import com.example.onepass.tv.model.TvChannel

/**
 * 频道 → 四大分类 的判定。
 *
 * 为什么用「名单 + 关键词」而不是纯关键词或机器学习：
 * IPTV 频道的名字是运营方随便起的（「电影周星星」「东森洋片」这种），任何通用规则都会误判。
 * 实测把两个源的分组和频道名都拉下来逐个看过之后，用「**精确名单兜底 + 关键词扩展**」最稳：
 *   - 名单里的是确定项，不会误判；
 *   - 关键词负责覆盖以后新冒出来的频道（比如新的「XX武侠剧场」）。
 *
 * 判定顺序很重要：**戏曲 > 古装 > 央视/卫视 > 其余归现代**。
 * 举例：CCTV-11 是戏曲频道，虽然分组是「央视」，但必须归到戏曲节目，所以戏曲要先判。
 */
object TvClassifier {

    // ---------------------------------------------------------------- 戏曲

    /**
     * **已知坏条目黑名单** —— 命中直接不展示。
     *
     * 这些都是远程源里混进来的、实测播不了的台，留着只会让老人点进去看到「这个台看不了」：
     *   · 陕西秦腔：地址是**测试卡**（彩条/风景图），不是真节目；
     *   · 移动戏曲：其公网镜像 1041 在 5 个可用主机上全部 400（实测），整个台是死的。
     */
    private val BLOCK_NAMES = setOf(
        "陕西秦腔", "移动戏曲"
    )

    /**
     * 确定是戏曲的频道名（CCTV11 就是戏曲频道，名字里却看不出「戏」字，必须单列）。
     *
     * 维护提醒：远程源里的「陕西秦腔」是测试卡，已用 [BLOCK_NAMES] 直接屏蔽，并且
     * 关键词里的「秦腔」也删掉了（双保险）。
     */
    private val OPERA_NAMES = setOf(
        "CCTV11", "CCTV-11", "梨园"
    )

    /** 戏曲剧种/栏目关键词，覆盖以后新增的戏曲频道 */
    private val OPERA_WORDS = listOf(
        "戏曲", "越剧", "黄梅", "京剧", "豫剧", "评剧", "曲剧", "梆子",
        "晋剧", "川剧", "沪剧", "锡剧", "淮剧", "粤剧", "潮剧", "花鼓", "采茶",
        "蒲剧", "眉户", "庐剧", "徽剧", "歌仔", "昆曲", "评弹", "梨园", "大戏台"
    )

    // ---------------------------------------------------------------- 古装

    /**
     * 确定是古装/武侠的频道名。
     * 来源：把远程源「电影频道」分组 78 个名字逐个过了一遍挑出来的。
     */
    private val COSTUME_NAMES = setOf(
        "倚天屠龙记", "射雕英雄传", "笑傲江湖", "神雕侠侣", "鹿鼎记", "天龙八部",
        "大唐双龙传", "寻秦记", "封神榜", "楚汉骄雄", "金枝欲孽", "西游记2",
        "倩女幽魂人间道", "倩女幽魂妖魔道", "倩女幽魂道道道",
        "金庸武侠", "武侠电影", "龙门飞甲", "狄仁杰电影", "活佛济公3", "洗冤录",
        "功夫电影", "电影功夫片"
    )

    /** 古装关键词（覆盖新增频道；刻意收得很紧，避免把现代剧误判进来） */
    private val COSTUME_WORDS = listOf(
        "古装", "武侠", "金庸", "古龙", "梁羽生", "倚天", "射雕", "神雕", "笑傲",
        "鹿鼎", "天龙八部", "封神", "楚汉", "金枝", "西游记", "大唐", "寻秦",
        "龙门", "狄仁杰", "倩女", "洗冤", "包青天", "聊斋", "三国", "水浒",
        "杨家将", "穆桂英", "白蛇", "锦衣", "笑傲江湖", "侠客", "江湖"
    )

    // ---------------------------------------------------------------- 直播频道

    /** 这些分组属于「打开就有」的电视台直播，归央视频道 */
    private val LIVE_GROUPS = setOf("央视", "卫视")

    // ---------------------------------------------------------------- 现代节目

    /**
     * **只有**这些分组的内容才进「现代节目」。
     *
     * 为什么必须卡一道门槛（踩过坑）：一开始把「没匹配上的一律归现代」，
     * 结果远程源里「地方频道」248 个、「直播中国」77 个、「春晚频道」22 个全灌进来了，
     * 现代节目一下变成 **489 个台** —— 比分类之前还乱。
     * 老人要的是「看剧、看电影」，不是要一个本地区县新闻台的通讯录。
     *
     * 分组名来自 [M3uParser] 归一化后的结果（电影频道 → 影视轮播、地方影视剧场 → 影视剧场）。
     */
    private val MODERN_GROUPS = setOf("影视轮播", "影视剧场")

    // ---------------------------------------------------------------- 判定

    /**
     * 判定一个频道属于哪一类。
     *
     * @return null = **不进任何分类，界面上看不到**。
     *         地方台 / 直播中国 / 春晚 / 纪录 / 儿童 / 音乐 / 体育 / 其他 都走这里被挡在外面。
     *         这是「频道太多了」的正解：不是把几百个台塞进四个筐，而是只留下老人真正会看的。
     */
    fun categoryOf(channel: TvChannel): TvCategory? {
        val name = channel.name
        // ⓞ 黑名单直接挡掉：远程源里的坏条目（测试卡 / 死台），别让老人点进去白等一趟
        if (name in BLOCK_NAMES) return null
        // ⓪ B站点播唱段：按分组直接归戏曲（名字是「豫剧-穆桂英挂帅-辕门外三声炮」这种，关键词也能命中，
        //    但显式判分组更稳，以后加「京剧唱段」这类新分组不会漏）
        if (channel.group == BiliClient.GROUP_OPERA_SINGLE) return TvCategory.OPERA
        // ① 戏曲优先：CCTV-11 分组是「央视」，但内容全是戏，必须先判走
        if (name in OPERA_NAMES || name.containsAny(OPERA_WORDS)) return TvCategory.OPERA
        // ② 古装/武侠
        if (name in COSTUME_NAMES || name.containsAny(COSTUME_WORDS)) return TvCategory.COSTUME
        // ③ 电视台直播
        if (channel.group in LIVE_GROUPS) return TvCategory.CCTV
        // ④ 影视剧/电影轮播
        if (channel.group in MODERN_GROUPS) return TvCategory.MODERN
        // ⑤ 其余一律不展示
        return null
    }

    private fun String.containsAny(words: List<String>): Boolean =
        words.any { contains(it) }
}
